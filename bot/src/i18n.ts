// format a string with {placeholders}; {{x}} renders a literal {x}
export function t(lang: Lang | undefined, key: string, kw: Record<string, any> = {}): string {
  const d = S[lang === "en" ? "en" : "fa"] || S.fa;
  const s = d[key] ?? S.fa[key] ?? key;
  return s
    .replace(/\{\{/g, "\u0000")
    .replace(/\}\}/g, "\u0001")
    .replace(/\{(\w+)\}/g, (m, k: string) => (kw[k] !== undefined ? String(kw[k]) : m))
    .replace(/\u0000/g, "{")
    .replace(/\u0001/g, "}");
}
